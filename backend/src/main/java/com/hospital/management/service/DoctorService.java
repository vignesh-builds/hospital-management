package com.hospital.management.service;

import com.hospital.management.dto.DoctorCreationResponse;
import com.hospital.management.exception.BadRequestException;
import com.hospital.management.exception.ResourceNotFoundException;
import com.hospital.management.model.Doctor;
import com.hospital.management.model.DoctorAvailability;
import com.hospital.management.model.User;
import com.hospital.management.repository.AppointmentRepository;
import com.hospital.management.repository.DoctorAvailabilityRepository;
import com.hospital.management.repository.DoctorRepository;
import com.hospital.management.repository.UserRepository;

import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.security.core.Authentication;
import org.springframework.security.core.context.SecurityContextHolder;
import org.springframework.security.crypto.password.PasswordEncoder;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.security.SecureRandom;
import java.util.List;

@Service
public class DoctorService {

    private static final String EMAIL_PATTERN = "^[^@\\s]+@[^@\\s]+\\.[^@\\s]+$";

    @Autowired
    private DoctorRepository doctorRepository;

    @Autowired
    private UserRepository userRepository;

    @Autowired
    private AppointmentRepository appointmentRepository;

    @Autowired
    private DoctorAvailabilityRepository doctorAvailabilityRepository;

    @Autowired
    private PasswordEncoder passwordEncoder;


    private static final SecureRandom SECURE_RANDOM = new SecureRandom();

    private static final String PASSWORD_CHARACTERS =
            "ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz"
            + "23456789@#$%";

    /**
     * Creates a doctor together with a DOCTOR login account.
     * A secure temporary password is generated by the system and returned
     * only in this response. The doctor must change it on first login.
     */
    @Transactional
    public DoctorCreationResponse createDoctor(Doctor doctor) {

        validate(doctor);

        doctor.setId(null);

        User input = doctor.getUser();

        if (input == null
                || input.getEmail() == null
                || input.getEmail().isBlank()) {
            throw new BadRequestException(
                    "Doctor email is required to create a login account");
        }

        String email = input.getEmail().trim().toLowerCase();

        if (!email.matches(EMAIL_PATTERN)) {
            throw new BadRequestException("Please enter a valid login email");
        }

        if (userRepository.findByEmailIgnoreCase(email).isPresent()) {
            throw new BadRequestException("Email already registered");
        }

        String temporaryPassword = generateTemporaryPassword();

        User user = new User();
        user.setName(doctor.getName().trim());
        user.setEmail(email);
        user.setPassword(passwordEncoder.encode(temporaryPassword));
        user.setRole("DOCTOR");
        user.setMustChangePassword(true);

        doctor.setName(doctor.getName().trim());
        doctor.setSpecialization(doctor.getSpecialization().trim());
        doctor.setUser(userRepository.save(user));

        Doctor saved = doctorRepository.save(doctor);

        return new DoctorCreationResponse(
                saved.getId(),
                saved.getName(),
                email,
                temporaryPassword,
                true
        );
    }

    private String generateTemporaryPassword() {

        int length = 14;
        StringBuilder password = new StringBuilder(length);

        for (int i = 0; i < length; i++) {
            password.append(PASSWORD_CHARACTERS.charAt(
                    SECURE_RANDOM.nextInt(PASSWORD_CHARACTERS.length())));
        }

        return password.toString();
    }

    public List<Doctor> getAllDoctors() {
        return doctorRepository.findAll();
    }

    public Doctor getDoctorById(Long id) {
        return doctorRepository.findById(id)
                .orElseThrow(() ->
                        new ResourceNotFoundException("Doctor not found"));
    }

    public Doctor getLoggedInDoctor() {

        Authentication authentication =
                SecurityContextHolder.getContext().getAuthentication();

        User user = userRepository.findByEmail(authentication.getName())
                .orElseThrow(() ->
                        new ResourceNotFoundException("User not found"));

        return doctorRepository.findByUserId(user.getId())
                .orElseThrow(() ->
                        new ResourceNotFoundException("Doctor profile not found"));
    }

    public Doctor updateDoctor(Long id, Doctor doctor) {

        validate(doctor);

        Doctor existingDoctor = getDoctorById(id);

        existingDoctor.setName(doctor.getName().trim());
        existingDoctor.setSpecialization(doctor.getSpecialization().trim());
        existingDoctor.setPhone(doctor.getPhone());

        // Optional profile details - only overwrite when provided
        if (doctor.getAge() != null) {
            existingDoctor.setAge(doctor.getAge());
        }
        if (doctor.getExperience() != null) {
            existingDoctor.setExperience(doctor.getExperience());
        }
        if (doctor.getQualification() != null) {
            existingDoctor.setQualification(doctor.getQualification());
        }
        if (doctor.getConsultationFee() != null) {
            existingDoctor.setConsultationFee(doctor.getConsultationFee());
        }

        return doctorRepository.save(existingDoctor);
    }

    @Transactional
    public void deleteDoctor(Long id) {

        Doctor doctor = getDoctorById(id);

        if (appointmentRepository.existsByDoctorId(id)) {
            throw new BadRequestException(
                    "This doctor has appointments. Delete or reassign them first.");
        }

        List<DoctorAvailability> availabilities =
                doctorAvailabilityRepository.findByDoctorId(id);
        doctorAvailabilityRepository.deleteAll(availabilities);

        User user = doctor.getUser();

        doctorRepository.delete(doctor);

        if (user != null) {
            userRepository.delete(user);
        }
    }

    private void validate(Doctor doctor) {

        if (doctor == null
                || doctor.getName() == null || doctor.getName().isBlank()
                || doctor.getSpecialization() == null
                || doctor.getSpecialization().isBlank()) {

            throw new BadRequestException(
                    "Doctor name and specialization are required");
        }

        if (doctor.getAge() != null
                && (doctor.getAge() < 0 || doctor.getAge() > 150)) {
            throw new BadRequestException("Age must be between 0 and 150");
        }

        if (doctor.getExperience() != null && doctor.getExperience() < 0) {
            throw new BadRequestException("Experience cannot be negative");
        }

        if (doctor.getConsultationFee() != null
                && doctor.getConsultationFee() < 0) {
            throw new BadRequestException(
                    "Consultation fee cannot be negative");
        }
    }
}
